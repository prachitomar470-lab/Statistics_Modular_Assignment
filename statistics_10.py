import numpy as np


np.random.seed(42)

delivery_time = np.random.normal(
    30, 10, 10000
)

sample_sizes = [50, 200, 500]

for n in sample_sizes:

    sample = np.random.choice(
        delivery_time,
        n,
        replace=False
    )

    average = np.mean(sample)

    std_error = np.std(delivery_time, ddof=1) / np.sqrt(n)

    print("Sample Size:", n)
    print("Average Delivery Time:", round(average, 2))
    print("Standard Error:", round(std_error, 2))
    print("-------------------------")

import pandas as pd
import numpy as np

np.random.seed(42)

teams = np.random.choice(
    ['CSK', 'MI', 'RCB', 'KKR', 'GT'],
    200,
    p=[0.30, 0.25, 0.20, 0.15, 0.10]
)

df = pd.DataFrame({
    'Fan_ID': range(1, 201),
    'Favorite_Team': teams
})


print("Team-wise Fan Count:")
print(df['Favorite_Team'].value_counts())

sample_list = []

for team in df['Favorite_Team'].unique():

    team_fans = df[
        df['Favorite_Team'] == team
    ]
    n = round(
        len(team_fans) / len(df) * 40
    )

    selected_fans = team_fans.sample(
        n=n,
        random_state=42
    )

    sample_list.append(selected_fans)


final_sample = pd.concat(sample_list)

print("\nSelected IPL Fans:")
print(final_sample)

print("\nTotal Selected Fans:", len(final_sample))

print("\nTeam-wise Sample:")
print(final_sample['Favorite_Team'].value_counts())