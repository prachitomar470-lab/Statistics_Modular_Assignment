import pandas as pd
import numpy as np
np.random.seed(42)

cities = np.random.choice(
    ['Ahmedabad', 'Surat', 'Vadodara'],
    1000,
    p=[0.5, 0.3, 0.2]
)

df = pd.DataFrame({
    'Order_ID': range(1, 1001),
    'City': cities
})


city_counts = df['City'].value_counts()

print("City-wise Orders:")
print(city_counts)


sample_data = []

for city in city_counts.index:

    city_data = df[df['City'] == city]

    sample_size = round(
        (len(city_data) / len(df)) * 60
    )

    selected = city_data.sample(
        n=sample_size,
        random_state=42
    )

    sample_data.append(selected)

final_sample = pd.concat(sample_data)

print("\nStratified Sample:")
print(final_sample)

print("\nTotal Sample:", len(final_sample))
print("\nCity-wise Sample:")
print(final_sample['City'].value_counts())

