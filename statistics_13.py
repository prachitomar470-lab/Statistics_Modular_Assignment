import numpy as np
from scipy import stats

delivery_time = [28, 32, 27, 35, 29,
                 31, 30, 33, 26, 34]

t_stat, p_value = stats.ttest_1samp(
    delivery_time, popmean=30
)

print("T-statistic:", t_stat)
print("P-value:", p_value)
if p_value < 0.05:
    print("Reject Null Hypothesis")
else:
    print("Fail to Reject Null Hypothesis")

import numpy as np
from scipy import stats

before = [5200, 6100, 4800, 7000, 5500,
          6300, 5900, 5100, 6800, 5600]

after = [6500, 7200, 6100, 8000, 6900,
         7500, 7100, 6400, 7900, 6800]

t_stat, p_value = stats.ttest_ind(
    after, before,
    equal_var=False,
    alternative='greater'
)

print("Before Average:", np.mean(before))
print("After Average:", np.mean(after))

print("T-statistic:", t_stat)
print("P-value:", p_value)

if p_value < 0.05:
    print("Steps increased significantly")
else:
    print("No significant increase")

