df = pd.read_csv('/content/stat15 data .csv')

# Calculate grand mean
grand_mean = df['purchase_value'].mean()

# Calculate group means
group_means = df.groupby('age_group')['purchase_value'].mean()

# Between group variance (mean square)
ss_between = 0

for group in df['age_group'].unique():

    values = df[df['age_group'] == group]['purchase_value']

    ss_between += len(values) * (
        values.mean() - grand_mean
    ) ** 2

df_between = 3 - 1

between_variance = ss_between / df_between

# Within group variance (mean square)
ss_within = 0

for group in df['age_group'].unique():

    values = df[df['age_group'] == group]['purchase_value']

    ss_within += ((values - values.mean()) ** 2).sum()

df_within = len(df) - 3

within_variance = ss_within / df_within

print("Between-group variance:", between_variance)

