print("Login Results:")
print(results)

from scipy.stats import binom

def upi_payment_probability(n, k, p):

    probability = binom.pmf(k, n, p)

    return probability


# Given values
result = upi_payment_probability(5, 3, 0.9)

print("Probability of exactly 3 successful payments:", result)
print("Percentage:", result * 100, "%")

from scipy.stats import poisson

# Average number of playlists
average = 4

# Exactly 6 playlists
result = poisson.pmf(6, average)

print("Probability of exactly 6 playlists:", result)
print("Percentage:", result * 100, "%")

