import numpy as np
import matplotlib.pyplot as plt

np.random.seed(42)

data = np.random.exponential(scale=50, size=100000)

sample_means = []

for i in range(1000):
    sample = np.random.choice(data, size=30)
    mean = np.mean(sample)
    sample_means.append(mean)

plt.hist(sample_means, bins=30, edgecolor='black')

plt.title("Central Limit Theorem")
plt.xlabel("Sample Means")
plt.ylabel("Frequency")

plt.show()

"""The Central Limit Theorem states that when we take many random samples from a population and calculate their means, the distribution of those means becomes approximately normal (bell-shaped), even if the original population is not normally distributed.

Example: Zomato order amounts

Suppose Zomato has different order amounts:
- Some customers order for ₹100.
- Some customers order for ₹300.
- Some customers order for ₹500.
- Some customers order for ₹1,000.
The original order amounts may have a skewed distribution.

Now, suppose we select 30 random orders and calculate their average amount. We repeat this process 1000 times.

The 1000 averages will form an approximately normal, bell-shaped distribution.

This happens because averaging many independent observations reduces the effect of unusually high or low values.

Flipkart can use the Central Limit Theorem to analyze customer order amounts. Suppose Flipkart wants to understand the average amount customers spend on online shopping. It can randomly select 30 orders from different customers and calculate their average order value. This process can be repeated 1000 times. The sample averages will approximately follow a normal distribution. Using this information, Flipkart can estimate the average customer spending, understand customer purchasing behavior, plan discounts, and make better business decisions.
"""

